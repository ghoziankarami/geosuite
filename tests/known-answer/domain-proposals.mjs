import {readFileSync, existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const sandbox={};vm.createContext(sandbox);
vm.runInContext(readFileSync(fileURLToPath(new URL((existsSync(fileURLToPath(new URL('../../../package.json',import.meta.url))) ? '../../../src/' : '../../src/')+'shared/geostat/domain-proposals.js',import.meta.url)),'utf8'),sandbox);
const owner=sandbox.OrebitDomainProposals;
const plain=x=>JSON.parse(JSON.stringify(x));
const dataset={cols:['hole_id','from_m','to_m','ni_pct','domain'],rows:[['A',0,1,1,'SAP'],['A',1,2,2,'LIM'],['B',0,1,null,'']]};
const before=JSON.stringify(dataset);
const tagged=dataset.rows.map((row,i)=>({row,label:['Low','High','Unknown'][i]}));
const proposal=owner.preview(dataset,tagged,{method:'grade',element:'ni_pct'});
assert.equal(JSON.stringify(dataset),before);
assert.throws(()=>owner.apply(dataset,proposal,''),/PROPOSAL_REASON_REQUIRED/);
const result=owner.apply(dataset,proposal,'Inspect populations separately',null);
assert.equal(JSON.stringify(dataset),before);
assert.deepEqual(plain(result.record.sourceDomains),['SAP','LIM','']);
assert.deepEqual(plain(result.data.rows.map(r=>r[3])),[1,2,null]);
assert.deepEqual(plain(result.data.rows.map(r=>r[4])),['Low','High','Unknown']);
assert.equal(result.record.role,'statistical_population');
assert.equal(owner.restore(plain(result.record),result.data).stale,false);
const stale={...result.data,rows:result.data.rows.map(r=>r.slice())};stale.rows[0][3]=1.5;
assert.equal(owner.restore(plain(result.record),stale).stale,true);
const undone=owner.undo(stale,result.record);
assert.deepEqual(plain(undone.data.rows.map(r=>r[4])),['SAP','LIM','']);
assert.equal(undone.data.rows[0][3],1.5);
assert.equal(undone.record,null);
assert.equal(undone.event.action,'undo');
assert.equal(owner.restoreHistory([result.event,undone.event],stale).length,2);
assert.throws(()=>owner.restoreHistory([{action:'undo',reason:'missing rows'}],stale),/DOMAIN_HISTORY_INVALID/);
dataset.rows[0][3]=8;
assert.throws(()=>owner.apply(dataset,proposal,'Changed grades'),/PROPOSAL_STALE/);
const wrong=plain(result.record);wrong.appliedLabels[0]='Changed';
assert.throws(()=>owner.restore(wrong,result.data),/DOMAIN_REVIEW_LABEL_MISMATCH/);
const noDomain={cols:['hole_id','ni_pct'],rows:[['A',1],['B',2]]};
const draft=owner.preview(noDomain,noDomain.rows.map(row=>({row,label:'HOST'})),{method:'lithology',element:'ni_pct'});
const applied=owner.apply(noDomain,draft,'Geological logs as population context');
assert.deepEqual(plain(owner.undo(applied.data,applied.record).data.cols),noDomain.cols);
assert.deepEqual(plain(owner.undo(applied.data,applied.record).data.rows),noDomain.rows);
console.log('PASS: independent statistical proposal preview/Apply/stale/restore/Undo, original labels and grades, additive legacy schema');
